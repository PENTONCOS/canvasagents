// Canvas Journal runtime wiring: the pure half of "one undo/redo history commit becomes one journal
// step". pages/canvas/project.tsx owns the React effect (the 180ms debounce, the snapshot stacks and
// the store write); every decision that needs no React lives here so bun:test can exercise it —
// which `seq` a new commit starts at, how the diffed entries are stamped with a single commit id and
// appended under the cap, and whether a journal loaded from persistence already matches what
// normalizeJournal would produce (so a clean project open never writes back).
//
// Framework-free: no React, no DOM, no store access. Nothing is mutated.

import { CANVAS_JOURNAL_LIMIT, appendJournalEntry, diffCanvasSnapshots, normalizeJournal, type CanvasJournalDiffOptions, type CanvasJournalSnapshot } from "@/lib/canvas/canvas-journal";
import { withJournalCommitId } from "@/lib/canvas/canvas-journal-steps";
import type { CanvasJournalActor, CanvasJournalEntry } from "@/types/canvas";

export type CanvasJournalCommitOptions = {
    // Shared by every entry one commit produces; one commit -> one step in the operations list.
    // Generated by the caller inside the debounce callback so a restarted debounce cannot split or
    // duplicate a step.
    commitId: string;
    now?: () => number; // epoch ms source, forwarded to the diff
    makeId?: () => string; // entry id source, forwarded to the diff
    limit?: number; // cap after appending; defaults to CANVAS_JOURNAL_LIMIT
};

export type CanvasJournalCommitResult = {
    entries: CanvasJournalEntry[]; // entries this commit produced, oldest first (empty when nothing changed)
    journal: CanvasJournalEntry[]; // the journal after the append, capped at the limit
    dropped: number; // how many oldest entries fell off the front to satisfy the cap
};

// The seq a new commit should start at: one past the newest recorded entry, so seq stays monotonic
// across cap drops instead of restarting at 0 (the panel sorts by seq). A malformed or absent tail
// seq restarts at 0 rather than propagating NaN.
export function nextJournalSeq(journal: readonly CanvasJournalEntry[] = []): number {
    const last = journal.length > 0 ? journal[journal.length - 1] : undefined;
    const seq = last?.seq;
    return typeof seq === "number" && Number.isFinite(seq) ? Math.floor(seq) + 1 : 0;
}

// Turns one history commit into journal entries. `prev`/`next` are the same snapshot pair the
// undo/redo stack compares (diffCanvasSnapshots reads only nodes/connections/title), every entry of
// the commit shares `commitId`, and the entries are appended one by one under the cap so an oversized
// commit cannot push the journal past its limit. A commit that changed nothing diffable yields no
// entries and an untouched journal, letting the caller skip the store write entirely.
export function commitCanvasJournal(
    prev: CanvasJournalSnapshot | null | undefined,
    next: CanvasJournalSnapshot | null | undefined,
    journal: readonly CanvasJournalEntry[] = [],
    actor: CanvasJournalActor,
    opts: CanvasJournalCommitOptions,
): CanvasJournalCommitResult {
    const limit = typeof opts.limit === "number" && Number.isFinite(opts.limit) ? opts.limit : CANVAS_JOURNAL_LIMIT;
    const diffOptions: CanvasJournalDiffOptions = { seqStart: nextJournalSeq(journal) };
    if (typeof opts.now === "function") diffOptions.now = opts.now;
    if (typeof opts.makeId === "function") diffOptions.makeId = opts.makeId;
    const entries = diffCanvasSnapshots(prev, next, actor, diffOptions).map((entry) => withJournalCommitId(entry, opts.commitId));

    let current = normalizeJournal(journal, limit);
    if (entries.length === 0) return { entries: [], journal: current, dropped: 0 };
    let dropped = 0;
    for (const entry of entries) {
        const appended = appendJournalEntry(current, entry, limit);
        current = appended.entries;
        dropped += appended.dropped;
    }
    return { entries, journal: current, dropped };
}

export type CanvasJournalRestoreResult = {
    journal: CanvasJournalEntry[]; // normalized, capped entries ([] when there is nothing usable)
    needsRewrite: boolean; // true when the stored value was not already in canonical form
};

// Normalizes a journal loaded from persistence (or anywhere untrusted) and reports whether the stored
// value differed from that canonical form. The caller writes back only when `needsRewrite` is true,
// so an already-clean project never re-persists on open and a load/save loop cannot start. A missing
// journal is canonical by definition and is not written back; a non-array value is dropped and
// rewritten once so the corrupt shape does not survive.
export function restoreCanvasJournal(stored: unknown, limit: number = CANVAS_JOURNAL_LIMIT): CanvasJournalRestoreResult {
    if (stored === undefined || stored === null) return { journal: [], needsRewrite: false };
    if (!Array.isArray(stored)) return { journal: [], needsRewrite: true };
    const journal = normalizeJournal(stored, limit);
    return { journal, needsRewrite: JSON.stringify(stored) !== JSON.stringify(journal) };
}
